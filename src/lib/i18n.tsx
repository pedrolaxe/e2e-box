const MESSAGES: Record<Lang, Messages> = { 'pt-BR': ptBR, en }

interface I18n {
  lang: Lang
  t: Messages
  setLang: (lang: Lang) => void
}

const I18nContext = createContext<I18n>({ lang: 'pt-BR', t: ptBR, setLang: () => undefined })

/** `initial` vem do layout (cookie ou Accept-Language): o HTML do servidor já sai no idioma certo. */
export function I18nProvider({ initial, children }: { initial: Lang; children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial)
  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    document.documentElement.lang = next
    document.cookie = `${LANG_COOKIE}=${next}; path=/; max-age=31536000; samesite=lax`
  }, [])
  const value = useMemo(() => ({ lang, t: MESSAGES[lang], setLang }), [lang, setLang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
